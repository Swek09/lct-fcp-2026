type Question struct {
	ID      string   `json:"id"`
	Prompt  string   `json:"prompt"`
	Topic   string   `json:"topic"`
	Kind    string   `json:"kind"`
	Options []string `json:"options"`
}
type PrivateQuestion struct {
	Question
	Expected string `json:"expected"`
}
type template struct {
	topic, prompt string
	choices       []string
}

func Valid(spec, grade string) bool {
	return (spec == "backend" || spec == "frontend" || spec == "analytics") && (grade == "junior" || grade == "middle" || grade == "senior")
}
func Generate(spec, grade string, seed uint64) []PrivateQuestion {
	r := rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))
	bank := banks[spec+"-"+grade]
	result := make([]PrivateQuestion, 0, 6)
	// Equal topic blueprint and scoring for all variants in the same category.
	for i, t := range bank {
		if i == 1 || i == 3 {
			result = append(result, scenario(spec, grade, i, r, t.topic))
			continue
		}
		opts := append([]string{}, t.choices...)
		expected := opts[0]
		r.Shuffle(len(opts), func(i, j int) { opts[i], opts[j] = opts[j], opts[i] })
		result = append(result, PrivateQuestion{Question: Question{ID: fmt.Sprintf("q%d", i+1), Prompt: t.prompt, Topic: t.topic, Kind: "choice", Options: opts}, Expected: expected})
	}
	n := r.IntN(9) + 2
	var prompt, answer, topic string
	switch spec {
	case "backend":
		if grade == "junior" {
			prompt = fmt.Sprintf("Обработчик последовательно делает %d запроса к БД по 20 мс каждый. Остальное время равно нулю. Сколько миллисекунд занимает обработка?", n)
			answer = fmt.Sprint(n * 20)
		} else if grade == "middle" {
			prompt = fmt.Sprintf("Сервис получает %d00 запросов/с. Каждый запрос занимает соединение БД на 50 мс. Каково среднее число одновременно занятых соединений при стабильной нагрузке? Ответ — число.", n)
			answer = fmt.Sprint(n * 5)
		} else {
			prompt = fmt.Sprintf("Пик — %d00 запросов/с, обработка — 40 мс. Планируем среднюю занятость пула не выше 50%%. Какой минимальный размер пула удовлетворяет расчёту? Ответ — целое число.", n)
			answer = fmt.Sprint(n * 8)
		}
		topic = "Расчёт нагрузки"
	case "frontend":
		if grade == "junior" {
			prompt = fmt.Sprintf("Контейнер шириной %d00 px имеет по 20 px padding слева и справа и box-sizing: border-box. Границ нет. Какова ширина области содержимого в px?", n)
			answer = fmt.Sprint(n*100 - 40)
		} else if grade == "middle" {
			rows, overscan := r.IntN(10)+8, r.IntN(5)+2
			prompt = fmt.Sprintf("В списке %d00 строк высотой 40 px. Окно высотой %d px, начало выровнено по строке, overscan — по %d строки с каждой стороны. Сколько строк отрисуется в середине списка?", n, rows*40, overscan)
			answer = fmt.Sprint(rows + 2*overscan)
		} else {
			prompt = fmt.Sprintf("Начальный JS — %d00 КБ, пропускная способность — 100 КБ/с. После code splitting начальный пакет уменьшился на 40%%. На сколько миллисекунд сократится загрузка? Задержки и сжатие игнорируем.", n)
			answer = fmt.Sprint(n * 400)
		}
		topic = "Расчёт интерфейса"
	case "analytics":
		if grade == "junior" {
			rate := r.IntN(20) + 5
			prompt = fmt.Sprintf("Из %d00 посетителей покупку сделали %d. Какова конверсия в процентах? Введите число без знака %%.", n, n*rate)
			answer = fmt.Sprint(rate)
		} else if grade == "middle" {
			base, delta := r.IntN(8)+5, r.IntN(4)+1
			prompt = fmt.Sprintf("В контрольной группе конверсия %d%%, в тестовой %d%%, по %d000 участников. Каков относительный прирост конверсии в процентах? Округлите до двух знаков.", base, base+delta, n)
			answer = fmt.Sprintf("%.2f", float64(delta)*100/float64(base))
		} else {
			prompt = fmt.Sprintf("Оценка эффекта — %d, стандартная ошибка — 2. Используем нормальное приближение и коэффициент 1,96. Какова нижняя граница 95%% интервала? Ответ округлите до двух знаков.", n+4)
			answer = fmt.Sprintf("%.2f", float64(n+4)-3.92)
		}
		topic = "Расчёт метрики"
	}
	result = append(result, PrivateQuestion{Question: Question{ID: "q6", Prompt: prompt, Topic: topic, Kind: "number", Options: []string{}}, Expected: answer})
	return result
}
func Public(qs []PrivateQuestion) []Question {
	out := make([]Question, 0, len(qs))
	for _, q := range qs {
		out = append(out, q.Question)
	}
	return out
}
func Score(qs []PrivateQuestion, answers map[string]string) (int, map[string]bool) {
	correct := 0
	topics := map[string]bool{}
	for _, q := range qs {
		v := strings.TrimSpace(answers[q.ID])
		pass := v == q.Expected
		if q.Kind == "number" {
			actual, err := strconv.ParseFloat(strings.ReplaceAll(v, ",", "."), 64)
			expected, expectedErr := strconv.ParseFloat(q.Expected, 64)
			pass = err == nil && expectedErr == nil && math.Abs(actual-expected) < 0.005
		}
		if pass {
			correct++
		}
		topics[q.Topic] = pass
	}
	if len(qs) == 0 {
		return 0, topics
	}
	return correct * 100 / len(qs), topics
}

